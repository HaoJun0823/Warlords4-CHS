def main():
    # 检查所有文案长度
    over = [(k, len(v)) for k, v in COMPACT.items() if len(v) > 37]
    print(f"文案数 {len(COMPACT)}，超过37字的: {over}")

    apply = "--apply" in sys.argv
    changed = 0
    for p in sorted(CHS.glob("*.xml")):
        s = p.read_bytes().decode("gbk")
        stem = p.stem
        out = []
        pos = 0
        hits = []
        for m in re.finditer(r'(<Text time="(\d+)">)([^<]*)(</Text>)', s):
            key = (stem, m.group(2))
            if key in COMPACT:
                new = COMPACT[key]
                if new != m.group(3):
                    out.append((m.start(), m.end(), m.group(1) + new + m.group(4)))
                    hits.append((m.group(2), len(m.group(3)), len(new)))
        if out and apply:
            for a, b, rep in reversed(out):
                s = s[:a] + rep + s[b:]
            p.write_bytes(s.encode("gbk"))
        if hits:
            changed += len(hits)
            print(f"{stem}: {hits}")
    print(f"{'已应用' if apply else '预览'} {changed} 处")


if __name__ == "__main__":
    main()
